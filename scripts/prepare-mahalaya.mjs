/**
 * Turns the delivered Mahalaya art in design/source/ into the layers the window
 * scene runs on, in public/scene/. Run by hand after new art lands; the output
 * is committed, so a normal build needs neither sharp nor this script:
 *
 *   node scripts/prepare-mahalaya.mjs
 *
 * Two jobs the art cannot be expected to arrive done:
 *
 *  1. **Cut the window out of the room.** The room came flattened, its window
 *     filled with a painted grey checkerboard instead of real transparency (a
 *     common generator tell). The sky has to show through there, so the
 *     checkerboard is keyed to alpha 0 — only the light, neutral pixels inside
 *     the window band, so the dark iron bars and the ochre walls survive. The
 *     bounding box of what is removed is the window, and the scene positions the
 *     sky, the sun and the city to sit inside it.
 *
 *  2. **Trim the radio.** It arrived isolated on transparency already, just with
 *     a generous margin and a little warm glow bleed, so it is only cropped to
 *     its own bounding box.
 *
 * The parallax layers (clouds, far and near city) already carry clean alpha and
 * are re-encoded as-is.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const at = (p) => fileURLToPath(new URL(p, import.meta.url));
const SRC = (f) => at(`../design/source/${f}`);
const OUT = at("../public/scene/");
mkdirSync(OUT, { recursive: true });

// ── 1. the room, with the window keyed out ────────────────────────────────
const roomImg = sharp(SRC("maha-room.png")).ensureAlpha();
const { data: rd, info: ri } = await roomImg.raw().toBuffer({ resolveWithObject: true });
const { width: RW, height: RH } = ri;

// Only touch the central band; the calendar and the bulb are light too but sit
// out at the sides, and must not be keyed.
const bandL = Math.floor(RW * 0.28);
const bandR = Math.floor(RW * 0.66);
let minX = RW, minY = RH, maxX = 0, maxY = 0;
for (let y = 0; y < RH; y++) {
  for (let x = bandL; x < bandR; x++) {
    const p = (y * RW + x) * 4;
    const r = rd[p], g = rd[p + 1], b = rd[p + 2];
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b);
    if (mx - mn < 18 && mn > 185) {
      rd[p + 3] = 0; // neutral + light = the checkerboard: cut it
      if (x < minX) minX = x; if (x > maxX) maxX = x;
      if (y < minY) minY = y; if (y > maxY) maxY = y;
    }
  }
}
const windowRect = {
  left: +(minX / RW).toFixed(4),
  top: +(minY / RH).toFixed(4),
  right: +(maxX / RW).toFixed(4),
  bottom: +(maxY / RH).toFixed(4),
};
await sharp(rd, { raw: { width: RW, height: RH, channels: 4 } })
  .webp({ quality: 90, alphaQuality: 100, effort: 5 })
  .toFile(`${OUT}maha-room.webp`);

// ── 2. the radio, trimmed to itself ───────────────────────────────────────
const radio = await sharp(SRC("maha-radio.png")).ensureAlpha().trim({ threshold: 8 }).toBuffer();
const radioMeta = await sharp(radio).metadata();
await sharp(radio).webp({ quality: 92, alphaQuality: 100, effort: 5 }).toFile(`${OUT}maha-radio.webp`);

// ── 2b. the "মা আসছেন" lettering ───────────────────────────────────────────
const maa = await sharp(SRC("maa.png")).ensureAlpha().trim({ threshold: 10 }).toBuffer();
const maaMeta = await sharp(maa).metadata();
await sharp(maa).webp({ quality: 92, alphaQuality: 100, effort: 5 }).toFile(`${OUT}maha-maa.webp`);

// ── 3. the parallax layers, as delivered ──────────────────────────────────
const layers = {};
for (const [file, out] of [
  ["maha-clouds.png", "maha-clouds"],
  ["maha-city-far.png", "maha-city-far"],
  ["maha-city-near.png", "maha-city-near"],
  ["maha-curtain.png", "maha-curtain"],
]) {
  const m = await sharp(SRC(file)).metadata();
  await sharp(SRC(file)).ensureAlpha().webp({ quality: 88, alphaQuality: 90, effort: 5 }).toFile(`${OUT}${out}.webp`);
  layers[out] = +(m.width / m.height).toFixed(4);
}

// ── 4. what the scene needs to know ───────────────────────────────────────
const geometry = {
  roomAspect: +(RW / RH).toFixed(4),
  window: windowRect,
  radioAspect: +(radioMeta.width / radioMeta.height).toFixed(4),
  maaAspect: +(maaMeta.width / maaMeta.height).toFixed(4),
  layers,
};

// content version, so the webp can be cached immutably yet update on change
const hash = createHash("sha1");
for (const f of ["maha-room", "maha-radio", "maha-maa", "maha-clouds", "maha-city-far", "maha-city-near", "maha-curtain"]) {
  hash.update(readFileSync(`${OUT}${f}.webp`));
}
hash.update(JSON.stringify(geometry));
const version = hash.digest("hex").slice(0, 8);

writeFileSync(
  at("../src/data/mahalayaGeometry.ts"),
  `// GENERATED by scripts/prepare-mahalaya.mjs. Do not edit by hand.
//
// Measured off the delivered art: the room's window opening after the painted
// checkerboard was keyed out, and each layer's aspect. The scene lays the sky,
// the sun and the city inside \`window\`, then the room on top masks the rest.

export const MAHALAYA_VERSION = "${version}";

export const MAHALAYA_GEOMETRY = {
  roomAspect: ${geometry.roomAspect},
  /** the window opening, as fractions of the room image */
  window: { left: ${windowRect.left}, top: ${windowRect.top}, right: ${windowRect.right}, bottom: ${windowRect.bottom} },
  radioAspect: ${geometry.radioAspect},
  maaAspect: ${geometry.maaAspect},
  layers: {
${Object.entries(layers).map(([k, v]) => `    "${k}": ${v},`).join("\n")}
  },
} as const;
`,
);

console.log(`[mahalaya] room     ${RW}x${RH}, window keyed`);
console.log(`[mahalaya] window   ${JSON.stringify(windowRect)}`);
console.log(`[mahalaya] radio    ${radioMeta.width}x${radioMeta.height} (aspect ${geometry.radioAspect})`);
for (const [k, v] of Object.entries(layers)) console.log(`[mahalaya] ${k.padEnd(14)} aspect ${v}`);
console.log(`[mahalaya] version  ${version}`);
