/**
 * Derive: the two ingest caches (filmography + extracts) -> the committed
 * src/data/uttamkumar/extracts.generated.ts a real build depends on.
 *
 * For every film whose Wikipedia table entry links to its own article, and
 * whose article actually resolved to a usable lead extract, this records
 * that extract plus a best-effort "directed by X" parse pulled straight out
 * of the extract's own prose (dropped silently if the regex doesn't find a
 * clean name — a missing director is honest, a wrong one isn't).
 *
 * films.ts decides at merge time whether to use this: a film with its own
 * hand-curated FILM_DETAILS entry keeps that; everything else falls back to
 * this extract, tagged `sourceKind: "wikipedia"` so the UI and the credits
 * page can attribute it correctly (Wikipedia's text is CC BY-SA 4.0 — reused
 * with attribution, not silently absorbed as this site's own prose).
 *
 * Usage: node scripts/prepare-uttamkumar-extracts.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CACHE_DIR = path.join(ROOT, "scripts", ".cache");
const FILMOGRAPHY = path.join(CACHE_DIR, "uttamkumar-filmography.json");
const EXTRACTS = path.join(CACHE_DIR, "uttamkumar-extracts.json");
const OUT = path.join(ROOT, "src", "data", "uttamkumar", "extracts.generated.ts");

function parseDirector(extract) {
  if (!extract) return undefined;
  const m = extract.match(
    /directed by ((?:[A-Z][\w'.’-]*\.?\s*){1,4}?)(?=[,.]|\s+(?:and|under|based|for|starring|with|of)\b|$)/,
  );
  if (!m) return undefined;
  const name = m[1].trim().replace(/\.$/, "");
  // Reject obvious mis-parses: too short, or clearly not a name (all lowercase).
  if (name.length < 3 || name === name.toLowerCase()) return undefined;
  return name;
}

function tsString(s) {
  return JSON.stringify(s ?? "");
}

const BENGALI_RUN = /[ঀ-৿][ঀ-৿\s,.'’-]*[ঀ-৿]|[ঀ-৿]/g;

/** This site's pages are English-only by policy (see the layout/nav copy);
 *  Wikipedia's own lead extracts routinely open with a native-script gloss,
 *  e.g. "(Bengali: দৃষ্টিদান, Donating Eyes)". Strips the script run and the
 *  redundant "Bengali:"/"Bengali-language" label, keeping any English gloss
 *  that follows it, then tidies up the punctuation left behind. */
function stripBengaliScript(text) {
  return text
    .replace(BENGALI_RUN, "")
    .replace(/\(\s*Bengali:\s*,?\s*/gi, "(")
    .replace(/\bBengali-language\b/gi, "Bengali")
    .replace(/\(\s*,\s*/g, "(")
    .replace(/\(\s*\)/g, "")
    .replace(/\s{2,}/g, " ")
    .replace(/\s+([,.);])/g, "$1")
    .replace(/\(\)\s*/g, "")
    .trim();
}

function main() {
  const filmography = JSON.parse(fs.readFileSync(FILMOGRAPHY, "utf8"));
  const extractData = JSON.parse(fs.readFileSync(EXTRACTS, "utf8"));

  const rows = [];
  for (const f of filmography.acting) {
    if (!f.wikiTarget) continue;
    const e = extractData.extracts[f.wikiTarget];
    if (!e || !e.extract || e.missing) continue;
    const extract = stripBengaliScript(e.extract.trim());
    rows.push({
      slug: f.slug,
      wikiTitle: f.wikiTarget,
      extract,
      director: parseDirector(extract),
    });
  }

  const lines = rows
    .map(
      (r) =>
        `  ${tsString(r.slug)}: { wikiTitle: ${tsString(r.wikiTitle)}, extract: ${tsString(r.extract)}${r.director ? `, director: ${tsString(r.director)}` : ""} },`,
    )
    .join("\n");

  const ts = `/**
 * GENERATED by scripts/prepare-uttamkumar-extracts.mjs from
 * scripts/fetch-uttamkumar-film-extracts.mjs's cache. Do not edit by hand.
 *
 * Wikipedia's own lead-paragraph summary for every film whose table entry
 * links to an article that actually exists — ${rows.length} of the 211.
 * Reused under CC BY-SA 4.0; see /uttamkumar/credits for the attribution
 * this requires, and films.ts for how it's merged with hand-curated detail.
 *
 * Fetched: ${extractData.fetched}
 */
export interface ArchiveExtract {
  wikiTitle: string;
  extract: string;
  director?: string;
}

export const ARCHIVE_EXTRACTS: Record<string, ArchiveExtract> = {
${lines}
};
`;
  fs.writeFileSync(OUT, ts);
  console.log(`wrote ${OUT} (${rows.length} films, ${rows.filter((r) => r.director).length} with a parsed director)`);
}

main();
